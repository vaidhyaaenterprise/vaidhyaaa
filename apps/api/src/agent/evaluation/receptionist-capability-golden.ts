function padMessages(messages: string[], category: string, count = 20): string[] {
  if (messages.length >= count) {
    return messages.slice(0, count);
  }
  return Array.from({ length: count }, (_, index) => messages[index % messages.length]!);
}

function classifierCases(
  category: string,
  messages: string[],
  expectedIntent: string,
): CapabilityEvaluationCase[] {
  return padMessages(messages, category).map((messageText, index) => ({
    id: `${category}_${index + 1}`,
    category,
    kind: 'classifier',
    messageText,
    input: { messageText, languageCode: 'ta_tanglish' },
    expectedIntent,
  }));
}

function routerCases(
  category: string,
  reasons: string[],
  expectedMatched: boolean,
  expectedServiceKey?: string,
): CapabilityEvaluationCase[] {
  return padMessages(reasons, category).map((reasonForVisit, index) => ({
    id: `${category}_${index + 1}`,
    category,
    kind: 'router',
    input: {
      clinicId: 'clinic-a',
      reasonForVisit,
      activeClinicServices: [ORTHO_SERVICE, DENTAL_SERVICE],
    },
    expectedMatched,
    ...(expectedServiceKey ? { expectedServiceKey } : {}),
  }));
}

function stateCases(
  category: string,
  cases: Array<{
    messageText: string;
    currentFlow: string;
    currentState: string;
    expectedRecognizedAs: string;
    referenceDate?: string;
    offeredSlots?: CapabilityEvaluationCase['offeredSlots'];
  }>,
): CapabilityEvaluationCase[] {
  const padded =
    cases.length >= 20
      ? cases.slice(0, 20)
      : Array.from({ length: 20 }, (_, index) => cases[index % cases.length]!);

  return padded.map((entry, index) => ({
    id: `${category}_${index + 1}`,
    category,
    kind: 'state_extractor',
    messageText: entry.messageText,
    currentFlow: entry.currentFlow,
    currentState: entry.currentState,
    referenceDate: entry.referenceDate ?? '2026-05-16',
    ...(entry.offeredSlots ? { offeredSlots: entry.offeredSlots } : {}),
    input: {
      messageText: entry.messageText,
      currentFlow: entry.currentFlow,
      currentState: entry.currentState,
      referenceDate: entry.referenceDate ?? '2026-05-16',
    },
    expectedRecognizedAs: entry.expectedRecognizedAs,
  }));
}

